%%% @doc A simple scheduler scheme for AO.
%%% This device expects a message of the form:
%%%     Process: `#{ id, Scheduler: #{ Authority } }'
%%% <pre>
%%% It exposes the following keys for scheduling:
%%%     `#{ method: GET, path: <<"/info">> }' ->
%%%         Returns information about the scheduler.
%%%     `#{ method: GET, path: <<"/slot">> }' -> `slot(Base, Req, Opts)'
%%%         Returns the current slot for a process.
%%%     `#{ method: GET, path: <<"/schedule">> }' -> `get_schedule(Base, Req, Opts)'
%%%         Returns the schedule for a process in a cursor-traversable format.
%%%    ` #{ method: POST, path: <<"/schedule">> }' -> `post_schedule(Base, Req, Opts)'
%%%         Schedules a new message for a process, or starts a new scheduler
%%%         for the given message.
%%% </pre>

-module(dev_scheduler).
-device_libraries([lib_process]).
%%% AO-Core API functions:
-export([info/0]).
%%% Local scheduling functions:
-export([schedule/3, router/4]).
%%% CU-flow functions:
-export([slot/3, status/3, next/3]).
-export([start/0, checkpoint/1]).
%%% Utility functions:
-export([parse_schedulers/1]).
%%% Test helper exports:
-export([test_process/0]).
-include("include/hb.hrl").
-include_lib("eunit/include/eunit.hrl").

%%% The maximum number of assignments that we will query/return at a time.
-define(MAX_ASSIGNMENT_QUERY_LEN, 1000).
%%% The timeout for a lookahead worker.
-define(LOOKAHEAD_TIMEOUT, 1500).

%% @doc Helper to ensure that the environment is started.
start() ->
    % We need the rocksdb backend to run for hb_cache module to work
    application:ensure_all_started(hb),
    <<I1:32/unsigned-integer, I2:32/unsigned-integer, I3:32/unsigned-integer>>
        = crypto:strong_rand_bytes(12),
    rand:seed(exsplus, {I1, I2, I3}),
    ok.

%% @doc This device uses a default_handler to route requests to the correct
%% function.
info() -> 
    #{
        exports =>
            [
                <<"status">>,
                <<"next">>,
                <<"schedule">>,
                <<"slot">>,
                <<"init">>,
                <<"checkpoint">>
            ],
        excludes => [set, keys],
        default => fun router/4
    }.

%% @doc General utility functions that are available to other modules.
parse_schedulers(SchedLoc) when is_list(SchedLoc) -> SchedLoc;
parse_schedulers(SchedLoc) when is_binary(SchedLoc) ->
    binary:split(
        binary:replace(SchedLoc, <<"\"">>, <<"">>, [global]),
        <<",">>,
        [global, trim_all]
    ).

%% @doc The default handler for the scheduler device.
router(_, Base, Req, Opts) ->
    ?event({scheduler_router_called, {req, Req}, {opts, Opts}}),
    schedule(Base, Req, Opts).

%% @doc Load the schedule for a process into the cache, then return the next
%% assignment. Assumes that Base is a `dev_process' or similar message, having
%% a `Current-Slot' key. It stores a local cache of the schedule in the
%% `priv/To-Process' key.
next(Base, Req, Opts) ->
    ?event(debug_next, {scheduler_next_called, {base, Base}, {req, Req}}),
    ?event(next, started_next),
    ?event(next_profiling, started_next),
    Schedule = message_cached_assignments(Base, Opts),
    LastProcessed =
        hb_util:int(
            hb_ao:get(
                <<"at-slot">>,
                Base,
                Opts#{ <<"hashpath">> => ignore }
            )
        ),
    ?event(next_profiling, got_last_processed),
    ?event(debug_next, {in_message_cache, {schedule, Schedule}}),
    ?event(next, {last_processed, LastProcessed, {message_cache, length(Schedule)}}),
    % Get the assignments from the message cache, local cache, or fetch from
    % the SU. Returns an ordered list of assignments.
    NextAssignment =
        find_next_assignment(
            Base,
            Req,
            Schedule,
            LastProcessed,
            Opts
        ),
    ?event(next_profiling, got_assignments),
    case NextAssignment of
        {error, Reason} ->
            ?event(next_profiling, got_no_assignments),
            {error, Reason};
        {ok, [], _} ->
            {error, #{
                <<"status">> => 404,
                <<"reason">> =>
                    <<"Requested slot not yet available in schedule.">>
            }
        };
        {ok, Assignments, Lookahead} ->
            ?event(next_profiling, got_assignments),
            validate_next_slot(Base, Assignments, Lookahead, LastProcessed, Opts)
    end.

%% @doc Validate the `next` slot generated by `find_next_assignment`.
validate_next_slot(Base, [NextAssignment|Assignments], Lookahead, Last, Opts) ->
    % Paranoia: Get the slot of the next assignment, to ensure that it is the
    % last processed slot + 1.
    NextAssignmentSlot =
        try hb_util:int(
            hb_ao:get(
                <<"slot">>,
                NextAssignment,
                Opts#{ <<"hashpath">> => ignore }
            )
        )
        catch
            error:badarg -> slot_not_processable
        end,
    ?event(next_profiling, found_next_assignment_slot),
    ?event(debug_next, {norm_assignments, Assignments}),
    ?event(next, {assignments_to_cache, length(Assignments)}),
    % Remove assignments that are below the last processed slot.
    ?event(debug_next,
        {calculating_next_from_assignments,
            {last_processed, Last},
            {next_slot_from_assignment, NextAssignmentSlot},
            {assignments_received, length(Assignments)}
        }),
    ExpectedSlot = Last + 1,
    case NextAssignmentSlot of
        ExpectedSlot ->
            ?event(next_profiling, setting_cache),
            ?event(next, {setting_cache, {assignments, length(Assignments)}}),
            NextState =
                case hb_util:atom(hb_opts:get(scheduler_in_memory_cache, true, Opts)) of
                    true ->
                        hb_private:set(
                            Base,
                            #{ <<"scheduler@1.0">> => #{
                                <<"assignments">> => Assignments,
                                <<"lookahead-worker">> => Lookahead
                            }},
                            Opts
                        );
                    false ->
                        Base#{
                            <<"scheduler@1.0">> => #{
                                <<"lookahead-worker">> => Lookahead
                            }
                        }
                end,
            ?event(debug_next,
                {next_returning,
                    {slot, NextAssignmentSlot},
                    {message, NextAssignment}
                }
            ),
            ?event(next, {next_returning, {slot, NextAssignmentSlot}}),
			?event(next_profiling, returning),
            {ok, #{ <<"body">> => NextAssignment, <<"state">> => NextState }};
        slot_not_processable ->
            {error,
                #{
                    <<"status">> => 500,
                    <<"reason">> =>
                        <<"Unprocessable slot value received in assignment.">>
                }
            };
        UnexpectedSlot ->
            {error,
                #{
                    <<"status">> => 404,
                    <<"reason">> =>
                        <<"Received assignment slot does not match expected slot.">>,
                    <<"unexpected-slot">> => UnexpectedSlot,
                    <<"expected-slot">> => ExpectedSlot
                }
            }
    end.

%% @doc Get the assignments for a process from the message cache, local cache,
%% or the inbox (thanks to a lookahead-worker).
find_next_assignment(_Base, _Req, Schedule = [_Next|_], _LastSlot, _Opts) ->
    {ok, Schedule, undefined};
find_next_assignment(Base, Req, _Schedule, LastSlot, Opts) ->
    ProcID = lib_process:process_id(Base, Req, Opts),
    LocalCacheRes =
        case hb_util:atom(hb_opts:get(scheduler_ignore_local_cache, false, Opts)) of
            true -> not_found;
            false ->
                check_lookahead_and_local_cache(Base, ProcID, LastSlot + 1, Opts)
        end,
    case LocalCacheRes of
        {ok, Worker, Assignment} ->
            ?event(debug_next,
                {in_cache,
                    {slot, LastSlot + 1},
                    {assignment, Assignment}
                }
            ),
            ?event(next_profiling, read_assignment),
            {ok, [Assignment], Worker};
        not_found ->
            {ok, RecvdAssignments} =
                hb_ao:resolve(
                    Base,
                    #{
                        <<"method">> => <<"GET">>,
                        <<"path">> => <<"schedule/assignments">>,
                        <<"from">> => LastSlot
                    },
                    Opts#{ <<"scheduler-follow-redirects">> => true }
                ),
            % Convert the assignments to an ordered list of messages,
            % after removing all keys before the last processed slot.
            {
                ok,
                hb_util:message_to_ordered_list(
                    maps:filter(
                        fun(<<"priv">>, _) -> false;
                            (<<"commitments">>, _) -> false;
                            (Slot, _) -> hb_util:int(Slot) > LastSlot
                        end,
                        RecvdAssignments
                    )
                ),
                undefined
            }
    end.

%% @doc Non-device exported helper to get the cached assignments held in a
%% process.
message_cached_assignments(Msg, Opts) ->
    hb_private:get(
        <<"scheduler@1.0/assignments">>,
        Msg,
        [],
        Opts
    ).

%% @doc Spawn a new Erlang process to fetch the next assignments from the local
%% cache, if we have them available.
spawn_lookahead_worker(ProcID, Slot, Opts) ->
    Caller = self(),
    spawn(
        fun() ->
            ?event(next_lookahead,
                {looking_ahead,
                    {proc_id, ProcID},
                    {slot, Slot},
                    {caller, Caller}
                }
            ),
            case dev_scheduler_cache:read(ProcID, Slot, Opts) of
                {ok, Assignment} ->
                    LoadedAssignment = hb_cache:ensure_all_loaded(Assignment, Opts),
                    Caller ! {assignment, ProcID, Slot, LoadedAssignment};
                not_found ->
                    fail
            end
        end
    ).

%% @doc Check if we have a result from a lookahead worker or from our local
%% cache. If we have a result in the local cache, we may also start a new
%% lookahead worker to fetch the next assignments if we have them locally, 
%% ahead of time. This can be enabled/disabled with the `scheduler_lookahead'
%% option.
check_lookahead_and_local_cache(Base, ProcID, TargetSlot, Opts) when is_map(Base) ->
    case hb_private:get(<<"scheduler@1.0/lookahead-worker">>, Base, Opts) of
        not_found ->
            check_lookahead_and_local_cache(undefined, ProcID, TargetSlot, Opts);
        LookaheadWorker ->
            check_lookahead_and_local_cache(LookaheadWorker, ProcID, TargetSlot, Opts)
    end;
check_lookahead_and_local_cache(Worker, ProcID, TargetSlot, Opts) when is_pid(Worker) ->
    receive
        {assignment, ProcID, OldSlot, _Assignment} when OldSlot < TargetSlot ->
            % The lookahead worker has found an assignment for a slot that is
            % before the target slot. We remove it from the cache and continue
            % searching.
            ?event(next_lookahead,
                {received_expired_assignment,
                    {slot, OldSlot},
                    {target_slot, TargetSlot}
                }
            ),
            check_lookahead_and_local_cache(Worker, ProcID, TargetSlot, Opts);
        {assignment, ProcID, TargetSlot, Assignment} ->
            % The lookahead worker has found an assignment for the target slot.
            % We return the assignment and stop searching. We will start a new
            % lookahead worker to fetch the next slot in the background again.
            NewWorker = spawn_lookahead_worker(ProcID, TargetSlot + 1, Opts),
            ?event(next_lookahead,
                {lookahead_worker_succeeded, {slot, TargetSlot}}
            ),
            {ok, NewWorker, Assignment}
    after ?LOOKAHEAD_TIMEOUT ->
        ?event(next_lookahead, {lookahead_read_timeout, {slot, TargetSlot}}),
        erlang:exit(Worker, timeout),
        check_lookahead_and_local_cache(undefined, ProcID, TargetSlot, Opts)
    end;
check_lookahead_and_local_cache(undefined, ProcID, TargetSlot, Opts) ->
    % The lookahead worker has not found an assignment for the target
    % slot yet, so we check our local cache.
    ?event(next_lookahead, {reading_local_cache, {slot, TargetSlot}}),
    case dev_scheduler_cache:read(ProcID, TargetSlot, Opts) of
        not_found -> not_found;
        {ok, Assignment} ->
            % We have an assignment in our local cache, so we return it.
            % Depending on the `scheduler_lookahead' option, we may also
            % start a new lookahead worker to fetch the next assignments
            % if we have them locally, ahead of time.
            Worker =
                case hb_opts:get(scheduler_lookahead, true, Opts) of
                    false -> undefined;
                    true ->
                        % We found the assignment in our local cache, so
                        % optionally spawn a new Erlang process to fetch
                        % the next assignments if we have them locally, 
                        % ahead of time.
                        spawn_lookahead_worker(ProcID, TargetSlot + 1, Opts)
                end,
            {ok, Worker, hb_cache:ensure_all_loaded(Assignment, Opts)}
    end.

%% @doc Returns information about the entire scheduler.
status(_M1, _M2, _Opts) ->
    ?event(getting_scheduler_status),
    Wallet = dev_scheduler_registry:get_wallet(),
    {ok,
        #{
            <<"address">> => hb_util:id(ar_wallet:to_address(Wallet)),
            <<"processes">> =>
                lists:map(
                    fun hb_util:id/1,
                    dev_scheduler_registry:get_processes()
                ),
            <<"cache-control">> => <<"no-store">>
        }
    }.

%% @doc A router for choosing between getting the existing schedule, or
%% scheduling a new message.
schedule(Base, Req, Opts) ->
    ?event({resolving_schedule_request, {req, Req}, {state_msg, Base}}),
    case hb_util:key_to_atom(hb_ao:get(<<"method">>, Req, <<"GET">>, Opts)) of
        post -> post_schedule(Base, Req, Opts);
        get -> get_schedule(Base, Req, Opts)
    end.

%% @doc Schedules a new message on the SU. Searches Base for the appropriate ID,
%% then uses the wallet address of the scheduler to determine if the message is
%% for this scheduler. If so, it schedules the message and returns the assignment.
post_schedule(Base, Req, Opts) ->
    ?event(scheduling_message),
    % Find the target message to schedule:
    RawToSched = find_message_to_schedule(Base, Req, Opts),
    % If the message can not be properly loaded, this will throw an error
    % before scheduling the message.
    try hb_cache:ensure_all_loaded(RawToSched, Opts) of
        ToSched ->
            case hb_ao:get(<<"type">>, ToSched, not_found, Opts) of
                <<"Scheduler-Transfer">> ->
                    % The message is a signed transfer marker from a prior
                    % scheduler: attempt to accept the process's next epoch.
                    accept_transfer(ToSched, Opts);
                _ ->
                    do_post_schedule(Base, Req, ToSched, Opts)
            end
    catch
        error:{necessary_message_not_found, _, _} ->
            {error,
                #{
                    <<"status">> => 404,
                    <<"body">> => <<"Cannot fully load message to schedule.">>
                }
            }
    end.

do_post_schedule(Base, Req, ToSched, Opts) ->
    ?event({to_sched, ToSched}),
    % Find the ProcessID of the target message:
    % - If it is a Process, use the ID of the message.
    % - If not, use the target as the ProcessID.
    ProcID = find_target_id(Base, Req, ToSched, Opts),
    ?event({proc_id, ProcID}),
    % Filter all unsigned keys from the source message.
    case hb_message:with_only_committed(ToSched, Opts) of
        {ok, OnlyCommitted} ->
            ?event(
                {post_schedule,
                    {schedule_id, ProcID},
                    {message, ToSched}
                }
            ),
            % Find the relevant scheduler server for the given process and
            % message, start a new one if necessary, or return a redirect to the
            % correct remote scheduler.
            case find_server(ProcID, Base, ToSched, Opts) of
                {local, PID} ->
                    ?event({scheduling_locally, {proc_id, ProcID}, {pid, PID}}),
                    Action =
                        hb_ao:get(<<"action">>, OnlyCommitted, not_found, Opts),
                    case Action of
                        <<"Request-Scheduler-Transfer">> ->
                            post_local_transfer(
                                ProcID,
                                PID,
                                OnlyCommitted,
                                Opts
                            );
                        _ ->
                            post_local_schedule(
                                ProcID,
                                PID,
                                OnlyCommitted,
                                Opts
                            )
                    end;
                {redirect, Redirect} ->
                    ?event({process_is_remote, {redirect, Redirect}}),
                    case hb_opts:get(scheduler_follow_redirects, true, Opts) of
                        true ->
                            ?event({proxying_to_remote_scheduler,
                                {redirect, Redirect},
                                {msg, OnlyCommitted}
                            }),
                            post_remote_schedule(
                                ProcID,
                                Redirect,
                                OnlyCommitted,
                                Opts
                            );
                        false -> {ok, Redirect}
                    end;
                {error, Error} ->
                    ?event({error_finding_scheduler, {error, Error}}),
                    {error, Error}
            end;
        {error, Err} ->
            {error,
                #{
                    <<"status">> => 400,
                    <<"body">> => <<"Message invalid: ",
                        "Committed components cannot be validated.">>,
                    <<"reason">> => Err
                }
            }
    end.

%% @doc Post schedule the message. `Req' by this point has been refined to only
%% committed keys, and to only include the `target' message that is to be
%% scheduled.
post_local_schedule(ProcID, PID, Req, Opts) ->
    % Should we verify the message again before scheduling?
    Verified =
        case hb_opts:get(verify_assignments, true, Opts) of
            true ->
                ?event(debug_scheduler_verify,
                    {verifying_message_before_scheduling, Req}
                ),
                Res = length(hb_message:signers(Req, Opts)) > 0
                    andalso hb_message:verify(Req, signers, Opts),
                ?event(debug_scheduler_verify, {verified, Res}),
                Res;
            accept_unsigned ->
                ?event(
                    debug_scheduler_verify,
                    {accepting_unsigned_message_before_scheduling, Req}
                ),
                hb_message:verify(Req, signers, Opts);
            false -> true
        end,
    ?event({verified, Verified}),
    % Handle scheduling of the message if the message is valid.
    case {Verified, hb_ao:get(<<"type">>, Req, Opts)} of
        {false, _} ->
            {error,
                #{
                    <<"status">> => 400,
                    <<"body">> => <<"Message is not valid.">>,
                    <<"reason">> => <<"Given message is invalid.">>
                }
            };
        {true, <<"Process">>} ->
            {ok, _} = hb_cache:write(Req, Opts),
            spawn(
                fun() ->
                    {ok, Results} = hb_client_remote:upload(Req, Opts),
                    ?event(
                        {uploaded_process, {proc_id, ProcID}, {results, Results}}
                    )
                end
            ),
            ?event(
                {registering_new_process,
                    {proc_id, ProcID},
                    {pid, PID},
                    {is_alive, is_process_alive(PID)}
                }
            ),
            schedule_or_redirect(ProcID, PID, Req, Opts);
        {true, _} ->
            ?event(
                {scheduling_message,
                    {proc_id, ProcID},
                    {pid, PID},
                    {is_alive, is_process_alive(PID)}
                }
            ),
            % If Request is not a process, use the ID of Base as the PID
            schedule_or_redirect(ProcID, PID, Req, Opts)
    end.

%% @doc Schedule a message with the local server, returning a redirect to the
%% successor scheduler if the process's schedule has been transferred away.
schedule_or_redirect(ProcID, PID, Req, Opts) ->
    case dev_scheduler_server:schedule(PID, Req) of
        {transferred, Next} -> redirect_to_successor(ProcID, Next, Opts);
        Assignment -> {ok, Assignment}
    end.

%% @doc Generate a redirect response to the successor scheduler of a process.
redirect_to_successor(ProcID, Next, Opts) ->
    case find_remote_scheduler(ProcID, Next, Opts) of
        {redirect, Redirect} -> {ok, Redirect};
        {error, Error} -> {error, Error}
    end.

%% @doc Terminate the local schedule of a process with a transfer marker, if
%% the request is authorized. The signed marker is returned to the caller and
%% forwarded to the successor scheduler, best-effort: the marker is uploaded
%% to Arweave and acceptance is idempotent, so any bearer may re-deliver it.
post_local_transfer(ProcID, PID, Req, Opts) ->
    Next = hb_ao:get(<<"next-scheduler">>, Req, not_found, Opts),
    maybe
        true ?= ?IS_ID(Next)
            orelse {error,
                #{
                    <<"status">> => 400,
                    <<"body">> =>
                        <<"Transfer request names no valid next-scheduler.">>
                }
            },
        true ?= not is_own_identity(Next, Opts)
            orelse {error,
                #{
                    <<"status">> => 400,
                    <<"body">> =>
                        <<"Transfer request names this scheduler itself.">>
                }
            },
        true ?= transfer_authorized(ProcID, Req, Opts)
            orelse {error,
                #{
                    <<"status">> => 403,
                    <<"body">> => <<"Transfer request is not authorized.">>
                }
            },
        case dev_scheduler_server:transfer(PID, Req, hb_util:human_id(Next)) of
            {transferred, Existing} ->
                redirect_to_successor(ProcID, Existing, Opts);
            Marker ->
                spawn(
                    fun() -> forward_transfer(ProcID, Marker, Next, Opts) end
                ),
                {ok, Marker}
        end
    end.

%% @doc Determine whether a transfer request is authorized: signed by the node
%% operator, or pushed from the process itself and signed by a member of the
%% node message's `scheduler-transfer-authority' list. The process defines
%% when a transfer occurs; the node defines who it trusts to deliver the
%% decision. The authorizing signature must cover the keys that define the
%% transfer (`action', `next-scheduler', `target'), so a signature over
%% unrelated content cannot be replayed to authorize a transfer.
transfer_authorized(ProcID, Req, Opts) ->
    Signers =
        verified_signers(
            Req,
            [<<"action">>, <<"next-scheduler">>, <<"target">>],
            Opts
        ),
    Operator = hb_opts:get(operator, undefined, Opts),
    (?IS_ID(Operator)
        andalso lists:member(hb_util:human_id(Operator), Signers))
        orelse authority_pushed(ProcID, Req, Signers, Opts).

%% @doc Return the authenticated committers of `Msg' over `RequiredKeys': the
%% committers whose commitment passes `authenticated_committer/4'. An unsigned
%% or invalidly-signed message has no verified signers.
verified_signers(Msg, RequiredKeys, Opts) ->
    Commitments = hb_maps:get(<<"commitments">>, Msg, #{}, Opts),
    lists:filtermap(
        fun(Commitment) ->
            authenticated_committer(Msg, Commitment, RequiredKeys, Opts)
        end,
        hb_maps:values(Commitments, Opts)
    ).

%% @doc Return `{true, Committer}' if a single commitment authenticates its
%% committer over the required keys, or `false' otherwise. The commitment's
%% `committer' field must be present, equal the address derived from its own
%% `keyid', cover every required key, and verify. The keyid match defeats a
%% relabeled `committer' field (which verification does not otherwise bind to
%% the key); the required, matching committer field defeats an unverified
%% keyid-only commitment; the key coverage defeats replaying a signature made
%% over unrelated content.
authenticated_committer(Msg, Commitment, RequiredKeys, Opts) ->
    Claimed = hb_maps:get(<<"committer">>, Commitment, undefined, Opts),
    Derived =
        try
            dev_httpsig_keyid:keyid_to_committer(
                hb_maps:get(<<"keyid">>, Commitment, undefined, Opts)
            )
        catch _:_ -> undefined
        end,
    case {Claimed, Derived} of
        {undefined, _} -> false;
        {_, undefined} -> false;
        _ ->
            Committer = hb_util:human_id(Claimed),
            case
                Committer =:= hb_util:human_id(Derived)
                    andalso commitment_covers(Commitment, RequiredKeys, Opts)
                    andalso hb_message:verify(Msg, [Committer], Opts)
            of
                true -> {true, Committer};
                false -> false
            end
    end.

%% @doc Check that a commitment's `committed' list includes every one of the
%% required keys, so the signature binds those keys' values.
commitment_covers(Commitment, RequiredKeys, Opts) ->
    Committed =
        [
            hb_ao:normalize_key(Key)
        ||
            Key <- hb_maps:get(<<"committed">>, Commitment, [], Opts)
        ],
    lists:all(
        fun(Key) -> lists:member(hb_ao:normalize_key(Key), Committed) end,
        RequiredKeys
    ).

%% @doc Check that a transfer request was pushed from the process itself and
%% committed by a trusted transfer authority.
authority_pushed(ProcID, Req, Signers, Opts) ->
    FromProcess = hb_ao:get(<<"from-process">>, Req, not_found, Opts),
    Authorities =
        [
            hb_util:human_id(Authority)
        ||
            Authority <- hb_opts:get(scheduler_transfer_authority, [], Opts)
        ],
    FromProcess =/= not_found
        andalso hb_util:human_id(FromProcess) =:= hb_util:human_id(ProcID)
        andalso lists:any(
            fun(Signer) -> lists:member(Signer, Authorities) end,
            Signers
        ).

%% @doc Check whether the given address is an identity operated by this node.
is_own_identity(Address, Opts) ->
    case hb_opts:as(Address, Opts) of
        {ok, _} -> true;
        {error, not_found} -> false
    end.

%% @doc Deliver a signed transfer marker to the successor scheduler, such that
%% it can open the process's next epoch. Best-effort: failures are only
%% logged, as the marker is uploaded to Arweave and acceptance is idempotent.
forward_transfer(ProcID, Marker, Next, Opts) ->
    case find_remote_scheduler(ProcID, Next, Opts) of
        {redirect, Redirect} ->
            Res = post_remote_schedule(ProcID, Redirect, Marker, Opts),
            ?event(scheduling,
                {forwarded_transfer,
                    {proc_id, ProcID},
                    {next, Next},
                    {res, Res}
                }
            );
        {error, Error} ->
            ?event(warning,
                {transfer_forward_failed,
                    {proc_id, ProcID},
                    {next, Next},
                    {error, Error}
                }
            )
    end.

%% @doc Accept a transfer marker naming an identity of this node as the
%% successor scheduler for a process. The marker must verify, be committed by
%% a scheduler of the process, and name an identity that this node operates.
%% The node must also hold no assignments for the process: a node's assignment
%% table always contains exactly one epoch.
accept_transfer(Marker, Opts) ->
    RawProcID = hb_ao:get(<<"process">>, Marker, not_found, Opts),
    Next = hb_ao:get(<<"next-scheduler">>, Marker, not_found, Opts),
    maybe
        true ?= ?IS_ID(RawProcID)
            orelse {error,
                #{
                    <<"status">> => 400,
                    <<"body">> => <<"Transfer marker names no valid process.">>
                }
            },
        ProcID = hb_util:human_id(RawProcID),
        % Fetch the process strictly by its content address: the marker's
        % `process' is the process ID, so the scheduler set we trust must come
        % from the message that hashes to it, never from request-supplied state.
        Proc =
            case hb_cache:read(ProcID, Opts) of
                {ok, P} -> P;
                _ -> not_found
            end,
        true ?= (Proc =/= not_found)
            orelse {error,
                #{
                    <<"status">> => 404,
                    <<"body">> =>
                        <<"Process to transfer is not available: ",
                            ProcID/binary>>
                }
            },
        true ?= marker_from_scheduler(Marker, Proc, Opts)
            orelse {error,
                #{
                    <<"status">> => 403,
                    <<"body">> =>
                        <<"Transfer marker is not committed by a scheduler ",
                            "of the process.">>
                }
            },
        true ?= (Next =/= not_found) andalso is_own_identity(Next, Opts)
            orelse {error,
                #{
                    <<"status">> => 403,
                    <<"body">> =>
                        <<"Transfer marker names another scheduler.">>
                }
            },
        true ?= (dev_scheduler_cache:list(ProcID, Opts) =:= [])
            orelse {error,
                #{
                    <<"status">> => 409,
                    <<"body">> =>
                        <<"Assignments already exist for the process ",
                            "on this node.">>
                }
            },
        ok ?= dev_scheduler_cache:write_transfer(Marker, Opts),
        PID = dev_scheduler_registry:find(ProcID, Proc, Opts),
        ?event(scheduling,
            {accepted_transfer,
                {proc_id, ProcID},
                {pid, PID}
            }
        ),
        {ok,
            #{
                <<"status">> => 200,
                <<"body">> => <<"Transfer accepted.">>
            }
        }
    end.

%% @doc Check that a transfer marker is verified and committed by one of the
%% schedulers that the process message names. Committers are derived from the
%% signing keys and must have committed the marker's defining keys, so neither
%% a forged `committer' field nor a replayed signature can impersonate a
%% scheduler.
marker_from_scheduler(Marker, Proc, Opts) ->
    Signers =
        verified_signers(
            Marker,
            [<<"type">>, <<"next-scheduler">>, <<"process">>],
            Opts
        ),
    SchedLoc =
        hb_ao:get_first(
            [
                {Proc, <<"scheduler">>},
                {Proc, <<"scheduler-location">>}
            ],
            not_found,
            Opts#{ <<"hashpath">> => ignore }
        ),
    Schedulers =
        lists:filtermap(
            fun(Scheduler) ->
                try {true, without_hint(Scheduler)}
                catch throw:{invalid_operation_target, _} -> false
                end
            end,
            case SchedLoc of
                not_found -> [];
                _ -> parse_schedulers(SchedLoc)
            end
        ),
    lists:any(fun(Signer) -> lists:member(Signer, Schedulers) end, Signers).

%% @doc Locate the correct scheduling server for a given process.
find_server(ProcID, Base, Opts) ->
    find_server(ProcID, Base, undefined, Opts).
find_server(ProcID, Base, ToSched, Opts) ->
    case get_hint(ProcID, Opts) of
        {ok, Hint} ->
            ?event({found_hint_in_proc_id, Hint}),
            generate_redirect(ProcID, Hint, Opts);
        not_found ->
            ?event({no_hint_in_proc_id, ProcID}),
            case dev_scheduler_registry:find(ProcID, false, Opts) of
                PID when is_pid(PID) ->
                    ?event({found_pid_in_local_registry, PID}),
                    {local, PID};
                not_found ->
                    ?event({no_pid_in_local_registry, ProcID}),
                    Proc = find_process_message(ProcID, Base, ToSched, Opts),
                    ?event({found_process, {process, Proc}, {base, Base}}),
                    SchedLoc =
                        hb_ao:get_first(
                            [
                                {Proc, <<"scheduler">>},
                                {Proc, <<"scheduler-location">>}
                            ] ++
                            case ToSched of
                                undefined -> [];
                                _ -> [{ToSched, <<"scheduler-location">>}]
                            end,
                            not_found,
                            Opts#{ <<"hashpath">> => ignore }
                        ),
                    ?event({sched_loc, SchedLoc}),
                    case SchedLoc of
                        not_found ->
                            {error, <<"No scheduler information provided.">>};
                        _ ->
                            ?event(
                                {confirming_if_scheduler_is_local,
                                    {addr, SchedLoc}
                                }
                            ),
                            ParsedLoc = parse_schedulers(SchedLoc),
                            case is_local_scheduler(ProcID, Proc, ParsedLoc, Opts) of
                                {ok, PID} ->
                                    % We are the scheduler. Start the server if
                                    % it has not already been started, with the
                                    % given options.
                                    {local, PID};
                                {transferred, Next} ->
                                    % The schedule was terminated on this node
                                    % by a transfer: redirect to the successor.
                                    find_remote_scheduler(ProcID, Next, Opts);
                                false ->
                                    case
                                        dev_scheduler_cache:read_transfer(
                                            ProcID,
                                            Opts
                                        )
                                    of
                                        {ok, _} ->
                                            % This node accepted the schedule
                                            % through a transfer: it is the
                                            % scheduler, despite the process's
                                            % own scheduler definition.
                                            server_result(
                                                ProcID,
                                                dev_scheduler_registry:find(
                                                    ProcID,
                                                    Proc,
                                                    Opts
                                                ),
                                                Opts
                                            );
                                        not_found ->
                                            % We are not the scheduler. Find it
                                            % and return a redirect.
                                            find_remote_scheduler(
                                                ProcID,
                                                ParsedLoc,
                                                Opts
                                            )
                                    end
                            end
                    end
            end
    end.

%% @doc Find the process message for a given process ID and base message.
find_process_message(ProcID, Base, ToSched, Opts) ->
    % Find the process from the message.
    MaybeProcessMsg =
        hb_ao:get(
            <<"process">>,
            Base,
            not_found,
            Opts#{ <<"hashpath">> => ignore }
        ),
    case MaybeProcessMsg of
        not_found ->
            ToSchedIsProc =
                (ToSched =/= undefined)
                andalso (hb_message:id(ToSched, all) == ProcID),
            case ToSchedIsProc of
                true -> ToSched;
                false ->
                    ?event(
                        {reading_cache,
                            {proc_id, ProcID},
                            {store, hb_opts:get(store, Opts)}
                        }
                    ),
                    case hb_message:id(Base, all) of
                        ProcID -> Base;
                        _ ->
                            case hb_cache:read(ProcID, Opts) of
                                {ok, P} -> P;
                                not_found ->
                                    throw({
                                        process_not_available,
                                        ProcID
                                    })
                            end
                    end
            end;
        P -> P
    end.

%% @doc Determine if a scheduler is local. If so, return `{ok, PID}'. If the
%% schedule was terminated on this node by a transfer, return `{transferred,
%% Next}'. Otherwise return `false'. We start the local server if we _can_ be
%% the scheduler and it does not already exist.
is_local_scheduler(_, _, [], _Opts) -> false;
is_local_scheduler(ProcID, ProcMsg, [Scheduler | Rest], Opts) ->
    case is_local_scheduler(ProcID, ProcMsg, Scheduler, Opts) of
        false -> is_local_scheduler(ProcID, ProcMsg, Rest, Opts);
        Result -> Result
    end;
is_local_scheduler(ProcID, ProcMsg, Scheduler, Opts) ->
    case hb_opts:as(Scheduler, Opts) of
        {ok, _} ->
            case dev_scheduler_registry:find(ProcID, ProcMsg, Opts) of
                {transferred, Next} -> {transferred, Next};
                PID -> {ok, PID}
            end;
        {error, _} -> false
    end.

%% @doc Resolve a scheduler server lookup into a `find_server' result: a live
%% server is local, while a server that has transferred its schedule away
%% redirects to the successor.
server_result(_ProcID, PID, _Opts) when is_pid(PID) ->
    {local, PID};
server_result(ProcID, {transferred, Next}, Opts) ->
    find_remote_scheduler(ProcID, Next, Opts).

%% @doc If a hint is present in the string, return it. Else, return not_found.
get_hint(Str, Opts) when is_binary(Str) ->
    case hb_opts:get(scheduler_follow_hints, true, Opts) of
        true ->
            case binary:split(Str, <<"?">>, [global]) of
                [_, QS] ->
                    QueryMap = hb_maps:from_list(uri_string:dissect_query(QS)),
                    case hb_maps:get(<<"hint">>, QueryMap, not_found, Opts) of
                        not_found -> not_found;
                        Hint -> {ok, Hint}
                    end;
                _ -> not_found
            end;
        false -> not_found
    end;
get_hint(_Str, _Opts) -> not_found.

%% @doc Generate a redirect message to a scheduler.
generate_redirect(ProcID, SchedulerLocation, Opts) ->
    Variant = hb_ao:get(<<"variant">>, SchedulerLocation, <<"ao.N.1">>, Opts),
    ?event({generating_redirect, {proc_id, ProcID}, {variant, Variant}}),
    RedirectLocation =
        case is_binary(SchedulerLocation) of
            true -> SchedulerLocation;
            false ->
                hb_ao:get_first(
                    [
                        {SchedulerLocation, <<"url">>},
                        {SchedulerLocation, <<"location">>}
                    ],
                    <<"/">>,
                    Opts
                )
        end,
    {redirect,
        #{
            <<"status">> => 307,
            <<"location">> => RedirectLocation,
            <<"body">> =>
                <<"Redirecting to scheduler: ", RedirectLocation/binary>>,
            <<"variant">> => Variant
        }
    }.

%% @doc Take a process ID or target with a potential hint and return just the
%% process ID.
without_hint(Target) when ?IS_ID(Target) ->
    hb_util:human_id(Target);
without_hint(Target) ->
    case binary:split(Target, [<<"?">>, <<"&">>], [global]) of
        [ProcID] when ?IS_ID(ProcID) -> hb_util:human_id(ProcID);
        _ -> throw({invalid_operation_target, Target})
    end.

%% @doc Use the SchedulerLocation to find the remote path and return a redirect.
%% If there are multiple locations, try each one in turn until we find the first
%% that matches.
find_remote_scheduler(_ProcID, [], _Opts) -> {error, not_found};
find_remote_scheduler(ProcID, [Scheduler | Rest], Opts) ->
    case find_remote_scheduler(ProcID, Rest, Opts) of
        {error, not_found} ->
            find_remote_scheduler(ProcID, Scheduler, Opts);
        {redirect, Redirect} ->
            {redirect, Redirect}
    end;
find_remote_scheduler(ProcID, Scheduler, Opts) ->
    % Parse the scheduler location to see if it has a hint. If there is a hint,
    % we will use it to construct a redirect message.
    case get_hint(Scheduler, Opts) of
        {ok, Hint} ->
            % We have a hint. Construct a redirect message.
            generate_redirect(ProcID, Hint, Opts);
        not_found ->
            case hb_ao:resolve(
                #{ <<"device">> => <<"location@1.0">> },
                #{ <<"path">> => Scheduler },
                Opts
            ) of
                {ok, SchedMsg} ->
                    % We have a cached scheduler location. Use it to construct a
                    % redirect message.
                    generate_redirect(ProcID, SchedMsg, Opts);
                {error, Error} ->
                    ?event({failed_to_find_scheduler_location, {error, Error}}),
                    {error, Error}
            end
    end.

%% @doc Returns information about the current slot for a process.
slot(M1, M2, Opts) ->
    ?event({getting_current_slot, {msg, M1}}),
    ProcID = find_target_id(M1, M2, Opts),
    case find_server(ProcID, M1, Opts) of
        {local, PID} ->
            ?event({getting_current_slot, {proc_id, ProcID}}),
            {Timestamp, Height, Hash} = ar_timestamp:get(),
            #{ current := CurrentSlot, epoch := Epoch, wallets := Wallets } =
                dev_scheduler_server:info(PID),
            {ok, #{
                <<"process">> => ProcID,
                <<"current">> => CurrentSlot,
                <<"epoch">> => Epoch,
                <<"timestamp">> => Timestamp,
                <<"block-height">> => Height,
                <<"block-hash">> => Hash,
                <<"cache-control">> => <<"no-store">>,
                <<"addresses">> => lists:map(fun hb_util:human_id/1, Wallets)
            }};
        {redirect, Redirect} ->
            case hb_opts:get(scheduler_follow_redirects, true, Opts) of
                false -> {ok, Redirect};
                true -> remote_slot(ProcID, Redirect, Opts)
            end;
        {error, Error} ->
            {error, Error}
    end.

%% @doc Get the current slot from a remote scheduler.
remote_slot(ProcID, Redirect, Opts) ->
    ?event({getting_remote_slot, {proc_id, ProcID}, {redirect, {explicit, Redirect}}}),
    Node = node_from_redirect(Redirect, Opts),
    ?event({getting_slot_from_node, {string, Node}}),
    remote_slot(
        hb_ao:get(<<"variant">>, Redirect, <<"ao.N.1">>, Opts),
        ProcID,
        Node,
        Opts
    ).

%% @doc Get the current slot from a remote scheduler, based on the variant of
%% the process's scheduler.
remote_slot(<<"ao.N.1">>, ProcID, Node, Opts) ->
    % The process is running on a mainnet AO-Core scheduler, so we can just
    % use the `/slot' endpoint to get the current slot.
    ?event({getting_slot_from_ao_core_remote,
        {path, {string, <<"/", ProcID/binary, "/slot">>}}}),
    hb_http:get(Node, <<ProcID/binary, "/slot">>, Opts);
remote_slot(<<"ao.TN.1">>, ProcID, Node, Opts) ->
    % The process is running on a testnet AO-Core scheduler, so we need to use
    % `/processes/procID/latest' to get the current slot.
    Path = << ProcID/binary, "/latest?process-id=", ProcID/binary>>,
    ?event({getting_slot_from_ao_core_remote, {path, {string, Path}}}),
    case hb_http:get(Node, Path, Opts#{ <<"http-client">> => httpc }) of
        {ok, Res} ->
            ?event({remote_slot_result, {res, Res}}),
            case hb_util:int(hb_ao:get(<<"status">>, Res, 200, Opts)) of
                200 ->
                    Body = hb_ao:get(<<"body">>, Res, Opts),
                    JSON = hb_json:decode(Body),
                    ?event({got_slot_response, {json, JSON}}),
                    % Convert the JSON object for the latest assignment into the
                    % standardized `~scheduler@1.0' format.
                    A =
                        dev_scheduler_formats:aos2_to_assignment(
                            JSON,
                            Opts
                        ),
                    ?event({got_slot_response, {assignment, A}}),
                    {ok, #{
                        <<"process">> => ProcID,
                        <<"current">> => hb_maps:get(<<"slot">>, A, undefined, Opts),
                        <<"timestamp">> => hb_maps:get(<<"timestamp">>, A, undefined, Opts),
                        <<"block-height">> => hb_maps:get(<<"block-height">>, A, undefined, Opts),
                        <<"block-hash">> => hb_util:encode(<<0:256>>),
                        <<"cache-control">> => <<"no-store">>
                    }};
                307 ->
                    ?event({generating_new_redirect, {redirect, Res}}),
                    % Maintain the same variant, but generate the redirect using
                    % the new location.
                    NewRedirect =
                        generate_redirect(
                            ProcID,
                            Res#{ <<"variant">> => <<"ao.TN.1">> },
                            Opts
                        ),
                    ?event({recursing_on_new_redirect, {redirect, NewRedirect}}),
                    remote_slot(ProcID, NewRedirect, Opts);
                _ ->
                    {error, Res}
            end;
        {error, Res} ->
            ?event({remote_slot_error, {error, Res}}),
            {error, Res}
    end.

%% @doc Generate and return a schedule for a process, optionally between
%% two slots -- labelled as `from' and `to'. If the schedule is not local,
%% we redirect to the remote scheduler or proxy based on the node opts.
get_schedule(Base, Req, Opts) ->
    ProcID = hb_util:human_id(find_target_id(Base, Req, Opts)),
    From =
        case hb_ao:get(<<"from">>, Req, not_found, Opts) of
            not_found -> 0;
            X when X < 0 -> 0;
            FromRes -> hb_util:int(FromRes)
        end,
    To =
        case hb_ao:get(<<"to">>, Req, not_found, Opts) of
            not_found -> undefined;
            ToRes -> hb_util:int(ToRes)
        end,
    Format = hb_ao:get(<<"accept">>, Req, <<"application/http">>, Opts),
    ?event(
        {parsed_get_schedule,
            {process, ProcID},
            {from, From},
            {to, To},
            {format, Format}
        }
    ),
    case find_server(ProcID, Base, Opts) of
        {local, _PID} ->
            generate_local_schedule(Format, ProcID, From, To, Opts);
        {redirect, Redirect} ->
            ?event({redirect_received, {redirect, Redirect}}),
            case hb_opts:get(scheduler_follow_redirects, true, Opts) of
                true ->
                    case get_remote_schedule(ProcID, From, To, Redirect, Opts) of
                        {ok, Res} ->
                            case uri_string:percent_decode(Format) of
                                <<"application/aos-2">> ->
                                    dev_scheduler_formats:assignments_to_aos2(
                                        ProcID,
                                        hb_ao:get(
                                            <<"assignments">>, Res, [], Opts),
                                        hb_util:atom(hb_ao:get(
                                            <<"continues">>, Res, false, Opts)),
                                        Opts
                                    );
                                _ ->
                                    {ok, Res}
                            end;
                        {error, Res} ->
                            {error, Res}
                    end;
                false ->
                    {ok, Redirect}
            end;
        {error, Error} ->
            {error, Error}
    end.

%% @doc Get a schedule from a remote scheduler, but first read all of the
%% assignments from the local cache that we already know about.
get_remote_schedule(RawProcID, From, To, Redirect, Opts) ->
    % If we are responding to a legacy scheduler request we must add one to the
    % `from' slot to account for the fact that the legacy scheduler gives us
    % the slots _after_ the stated nonce.
    ProcID = without_hint(RawProcID),
    {FromLocalCache, _} = get_local_assignments(ProcID, From, To, Opts),
    ?event(debug_sched,
        {from_local_cache,
            {from, From},
            {to, To},
            {read, length(FromLocalCache)}
        }
    ),
    do_get_remote_schedule(
        ProcID,
        FromLocalCache,
        From + length(FromLocalCache),
        To,
        Redirect,
        Opts
    ).

%% @doc Get a schedule from a remote scheduler, unless we already have already
%% read all of the assignments from the local cache.
do_get_remote_schedule(ProcID, LocalAssignments, From, To, _, Opts)
        when (To =/= undefined) andalso (From >= To) ->
    % We already have all of the assignments from the local cache. Return them
    % as a bundle. We set the 'more' to `undefined' to indicate that there may
    % be more assignments to fetch, but we don't know for sure.
    Res = 
        dev_scheduler_formats:assignments_to_bundle(
            ProcID,
            LocalAssignments,
            undefined,
            Opts
        ),
    ?event(debug_sched,
        {returning_remote_schedule_from_only_cache,
            {length, length(LocalAssignments)},
            {from_after_local_cache, From},
            {original_to, To}
        }),
    Res;
do_get_remote_schedule(ProcID, LocalAssignments, From, To, Redirect, Opts) ->
    % We don't have all of the assignments from the local cache, so we need to
    % fetch the rest from the remote scheduler.
    Node = node_from_redirect(Redirect, Opts),
    Variant = hb_ao:get(<<"variant">>, Redirect, <<"ao.N.1">>, Opts),
    ?event(
        {getting_remote_schedule,
            {node, {string, Node}},
            {proc_id, {string, ProcID}},
            {from, From},
            {to, To}
        }
    ),
    MaybeNonce =
        if Variant == <<"ao.TN.1">> -> <<"-nonce">>;
        true -> <<>>
        end,
    FromBin =
        case From of
            undefined -> <<>>;
            From ->
                % The legacy scheduler gives us the slots _after_ the stated 
                % nonce. So we need to subtract one from the nonce to get the
                % correct slot.
                ModFrom =
                    if Variant == <<"ao.TN.1">> -> From - 1;
                    true -> From
                    end,
                <<
                    "&from",
                    MaybeNonce/binary,
                    "=",
                    (integer_to_binary(ModFrom))/binary
                >>
        end,
    ToParam =
        case To of
            undefined -> <<>>;
            To ->
                <<
                    "&to", MaybeNonce/binary, "=", (integer_to_binary(To))/binary
                >>
        end,
    Path =
        case Variant of
            <<"ao.N.1">> ->
                <<
                    ProcID/binary,
                    "/schedule?from=", FromBin/binary, ToParam/binary
                >>;
            <<"ao.TN.1">> ->
                <<
                    ProcID/binary, "?process-id=", ProcID/binary,
                    FromBin/binary, ToParam/binary,
                    "&limit=", (hb_util:bin(?MAX_ASSIGNMENT_QUERY_LEN))/binary
                >>
        end,
    ?event({getting_remote_schedule, {node, {string, Node}}, {path, {string, Path}}}),
    case
        hb_http:get(
            Node,
            Path,
            Opts#{ <<"http-client">> => httpc, <<"protocol">> => http2 }
        )
    of
        {ok, Res} ->
            case hb_util:int(hb_ao:get(<<"status">>, Res, 200, Opts)) of
                200 ->
                    {ok, NormSched} = 
                        case Variant of
                            <<"ao.N.1">> ->
                                cache_remote_schedule(Variant, ProcID, Res, Opts),
                                {ok, Res};
                            <<"ao.TN.1">> ->
                                JSONRes =
                                    hb_json:decode(
                                        hb_ao:get(
                                            <<"body">>,
                                            Res,
                                            <<"">>,
                                            Opts#{ <<"hashpath">> => ignore }
                                        )
                                    ),
                                cache_remote_schedule(Variant, ProcID, JSONRes, Opts),
                                ?event(debug_aos2, {json_res, {json, JSONRes}}),
                                Filtered = filter_json_assignments(JSONRes, To, From, Opts),
                                dev_scheduler_formats:aos2_to_assignments(
                                    ProcID,
                                    Filtered,
                                    Opts
                                )
                        end,
                    % Add existing local assignments we read to the remote schedule.
                    % In order to do this, we need to first convert the remote
                    % assignments to a list, maintaining the order of the keys.
                    RemoteAssignments =
                        hb_util:message_to_ordered_list(
                            hb_ao:normalize_keys(
                                hb_ao:get(
                                    <<"assignments">>,
                                    NormSched,
                                    Opts
                                ),
								Opts
                            )
                        ),
                    % Merge the local assignments with the remote assignments,
                    % and normalize the keys.
                    Merged =
                        dev_scheduler_formats:assignments_to_bundle(
                            ProcID,
                            MergedAssignments = LocalAssignments ++ RemoteAssignments,
                            hb_ao:get(<<"continues">>, NormSched, false, Opts),
                            Opts
                        ),
                    ?event(debug_sched,
                        {returning_remote_schedule,
                            {length, length(MergedAssignments)},
                            {from_local_cache, length(LocalAssignments)},
                            {from_remote_cache, length(RemoteAssignments)}
                        }
                    ),
                    Merged;
                307 ->
